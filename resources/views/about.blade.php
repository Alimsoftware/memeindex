        <section id="regras" class="doc-section">
            <h2>Regras de conteúdo</h2>
            <ul>
                <li>Todo envio é revisado por uma pessoa antes de ser publicado. A moderação pode aprovar ou rejeitar, e
                    quando rejeita o motivo aparece no seu perfil.</li>
                <li><strong>Conteúdo gore é proibido.</strong></li>
                <li>Não enviamos nem aceitamos conteúdo ilegal.</li>
                <li>Qualquer pessoa logada pode denunciar um meme pelo botão <strong>Reportar</strong>. As denúncias vão
                    para a fila da moderação.</li>
                <li>Memes duplicados ou fora do escopo do arquivo podem ser rejeitados.</li>
            </ul>
        </section>

        <section id="dmca" class="doc-section">
            <h2>Direitos autorais (DMCA)</h2>
            <p>Respeitamos os direitos de quem criou o conteúdo. Se você é titular de um direito (ou o representa) e
                acredita que um meme do índice o viola, peça a remoção.</p>

            <h3>Como pedir a remoção</h3>
            <ol>
                <li>Abra o meme e clique em <strong>Reportar</strong>. É preciso estar logado.</li>
                <li>Escolha o motivo <strong>“Violação de direitos autorais”</strong>.</li>
                <li>No campo de detalhes, explique o pedido com as informações abaixo.</li>
            </ol>
            <p>Se não conseguir usar o botão, fale com a gente pelos canais da seção <a href="#contato">Contato</a>.</p>

            <h3>O que incluir no pedido</h3>
            <ul>
                <li>Qual é a obra protegida e que você é a pessoa titular ou a representa.</li>
                <li>O endereço (URL) ou o título do meme que você quer ver removido.</li>
                <li>Seus dados para contato.</li>
                <li>Uma declaração de que você acredita, de boa-fé, que o uso não é autorizado.</li>
                <li>Uma declaração de que as informações do pedido são verdadeiras.</li>
            </ul>
            <p class="notice">A moderação analisa o pedido e, se confirmado, o meme é removido do índice.</p>
        </section>

